#!/bin/bash
# Cross-compile FFmpeg without fetching branches, tags, submodules or packages.
set -euo pipefail
umask 022
cd /work
mapfile -t fields < <(python3 - <<'PY'
import json
l=json.load(open('/work/control/lock.json'))
b={x['id']:x for x in l['blobs']}
print('/inputs/'+b[l['ffmpeg']['blobId']]['file'])
print(l['ffmpeg']['revision'])
print(l['ffmpeg']['sourceDateEpoch'])
print(l['recipe']['revision'])
print(l['buildId'])
PY
)
[[ ${#fields[@]} == 5 ]]
python3 control/safe_extract.py "${fields[0]}" ffmpeg-unpacked
mapfile -t roots < <(find ffmpeg-unpacked -mindepth 1 -maxdepth 1 -type d)
[[ ${#roots[@]} == 1 ]]
mv "${roots[0]}" ffmpeg-source
cd ffmpeg-source
[[ -f configure && -f COPYING.GPLv3 && -f libavcodec/avcodec.h ]]
export SOURCE_DATE_EPOCH="${fields[2]}"
export TZ=UTC LC_ALL=C.UTF-8
mkdir -p /work/configuration
python3 /work/control/capture_environment.py > /work/configuration/build-environment.json
"$CC" --version > /work/configuration/compiler-version.txt
"$CXX" --version > /work/configuration/compiler-cxx-version.txt
"$LD" --version > /work/configuration/linker-version.txt
dpkg-query -W -f='${Package}\t${Version}\n' > /work/configuration/compiler-image-packages.txt
find "$FFBUILD_PREFIX" -type f -print0 | sort -z | xargs -0 sha256sum > /work/configuration/dependency-prefix-sha256.txt
if [[ -d "$FFBUILD_PREFIX/share/duskcut-build" ]]; then
    cp -a "$FFBUILD_PREFIX/share/duskcut-build" /work/configuration/dependency-settings
fi
for runtime in libgcc.a libgcc_eh.a libstdc++.a libmingw32.a libmingwex.a libmsvcrt.a; do
    runtime_path="$("$CC" -print-file-name="$runtime")"
    if [[ -f "$runtime_path" ]]; then
        sha256sum "$runtime_path"
    else
        printf 'not-present\t%s\n' "$runtime"
    fi
done > /work/configuration/compiler-runtime-archive-sha256.txt
# FF_CONFIGURE and target flags are generated by the fixed upstream recipe.
# Shell word splitting is intentional for its configure flag lists, never eval.
# --trace retains actual archive/object linkage for a separate runtime review.
mapfile -t profile_flags < <(python3 - <<'PY'
import json
for flag in json.load(open('/work/control/profile.json'))['configureFlags']:
    print(flag)
PY
)
./configure --prefix=/work/binary --pkg-config-flags='--static' \
    $FFBUILD_TARGET_FLAGS $FF_CONFIGURE \
    "${profile_flags[@]}" \
    --extra-cflags="$FF_CFLAGS" --extra-cxxflags="$FF_CXXFLAGS" \
    --extra-libs="$FF_LIBS" --extra-ldflags="$FF_LDFLAGS" \
    --extra-ldexeflags="$FF_LDEXEFLAGS -Wl,--trace" \
    --cc="$CC" --cxx="$CXX" --ar="$AR" --ranlib="$RANLIB" --nm="$NM" \
    --extra-version="${fields[4]}"
cp config.h config_components.h config.asm /work/configuration/
cp ffbuild/config.mak ffbuild/config.log /work/configuration/
if grep -E '^#define CONFIG_LIBDVD(NAV|READ) 1$' config.h; then
    echo 'DVD libraries unexpectedly enabled' >&2
    exit 1
fi
make -j"$(nproc)" V=1
make install install-doc
cp COPYING.GPLv3 /work/binary/LICENSE.txt
for program in ffmpeg ffprobe; do
    "${FFBUILD_CROSS_PREFIX}objdump" -p "/work/binary/bin/$program.exe" > "/work/configuration/$program-pe-imports.txt"
done
find /work/binary -type f -print0 | sort -z | xargs -0 sha256sum > /work/configuration/binary-sha256.txt
# The public source snapshot and build tree both remain available. No upstream
# cleanup runs; generated config, patch inputs and complete logs are preserved.
python3 - "${fields[1]}" "${fields[3]}" "${fields[4]}" <<'PY'
import json,pathlib,sys
pathlib.Path('/work/compile-result.json').write_text(json.dumps({
    'ffmpegRevision':sys.argv[1], 'recipeRevision':sys.argv[2],
    'buildId':sys.argv[3],
    'licenseApproval':'not performed by build script',
    'functionalApproval':'not performed by build script'
},indent=2)+'\n')
PY
